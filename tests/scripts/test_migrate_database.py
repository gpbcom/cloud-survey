from __future__ import annotations

from pathlib import Path
from typing import List, Tuple
from unittest.mock import MagicMock, patch

import pytest
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected, CommandError

from models.configuration.storage.storage_settings import StorageSettings
from scripts.exception import MigrationError
from scripts.migrate_database import DatabaseMigrator
from storage.tables.schema import StorageSchema

SETTINGS = StorageSettings(url="postgresql+asyncpg://crawler:p%40ss@localhost:5432/poc_crawler")


def test_the_configuration_is_built_without_an_ini_file() -> None:
    migrator = DatabaseMigrator(SETTINGS)

    assert migrator.config.get_main_option("script_location") == str(DatabaseMigrator.MIGRATIONS_DIR)
    assert migrator.config.get_main_option("sqlalchemy.url") == SETTINGS.url
    assert "p%40ss" not in migrator.url


def test_the_code_expects_the_last_migration() -> None:
    head = ScriptDirectory.from_config(DatabaseMigrator(SETTINGS).config).get_current_head()

    assert head == StorageSchema.REVISION
    assert DatabaseMigrator(SETTINGS)._next_revision_id() == f"{int(head) + 1:04d}"
    assert DatabaseMigrator(SETTINGS).history()[0].startswith("0001: Initial storage schema")


@pytest.mark.parametrize(
    ("argv", "called"),
    [
        (["upgrade"], ("upgrade", ("head",))),
        (["upgrade", "0001"], ("upgrade", ("0001",))),
        (["downgrade", "base"], ("downgrade", ("base",))),
        (["check"], ("check", ())),
    ],
)
def test_the_commands_run_alembic(argv: List[str], called: Tuple[str, Tuple[str, ...]]) -> None:
    migrator = DatabaseMigrator(SETTINGS)
    with (
        patch(f"scripts.migrate_database.command.{called[0]}") as alembic,
        patch.object(DatabaseMigrator, "seed") as seed,
    ):
        assert migrator.parse(argv) == 0

    alembic.assert_called_once_with(migrator.config, *called[1])
    assert seed.called == (argv == ["upgrade"]), "an upgrade to the head seeds the taxonomy"


@pytest.mark.parametrize(("argv", "force"), [(["seed"], False), (["seed", "--force"], True)])
def test_the_seed_command_seeds_the_taxonomy(argv: List[str], force: bool) -> None:
    migrator = DatabaseMigrator(SETTINGS)
    with patch.object(DatabaseMigrator, "_seed", return_value=True) as seed:
        assert migrator.parse(argv) == 0

    seed.assert_called_once_with(force)


def test_a_failing_seed_is_a_migration_error() -> None:
    migrator = DatabaseMigrator(SETTINGS)
    with patch.object(DatabaseMigrator, "_seed", side_effect=OSError("unreachable")):
        assert migrator.parse(["seed"]) == 1


def test_a_new_revision_is_numbered_after_the_head(tmp_path: Path) -> None:
    migrator = DatabaseMigrator(SETTINGS)
    following = f"{int(StorageSchema.REVISION) + 1:04d}"
    script = MagicMock(path=str(tmp_path / f"{following}_add.py"))
    with patch("scripts.migrate_database.command.revision", return_value=script) as revision:
        assert migrator.revision("Add", autogenerate=True) == tmp_path / f"{following}_add.py"

    revision.assert_called_once_with(migrator.config, message="Add", autogenerate=True, rev_id=following)


@pytest.mark.parametrize(
    ("name", "error"),
    [
        ("upgrade", CommandError("no such revision")),
        ("downgrade", CommandError("no such revision")),
        ("check", AutogenerateDiffsDetected("differs", None, None)),  # type: ignore[arg-type]
        ("check", OSError("unreachable")),
        ("revision", CommandError("conflict")),
    ],
)
def test_a_failing_command_is_reported(name: str, error: Exception) -> None:
    migrator = DatabaseMigrator(SETTINGS)
    argv = {
        "upgrade": ["upgrade"],
        "downgrade": ["downgrade", "x"],
        "check": ["check"],
        "revision": ["revision", "-m", "x"],
    }
    with patch(f"scripts.migrate_database.command.{name}", side_effect=error):
        assert migrator.parse(argv[name]) == 1


def test_the_revision_of_an_unreachable_database_is_reported() -> None:
    migrator = DatabaseMigrator(StorageSettings(url="postgresql+asyncpg://u:p@127.0.0.1:9/nowhere"))

    with pytest.raises(MigrationError, match="current"):
        migrator.current()


@pytest.mark.db
def test_the_migrations_go_down_and_up_again(database_url: str, capsys: pytest.CaptureFixture[str]) -> None:
    migrator = DatabaseMigrator(StorageSettings(url=database_url))

    migrator.downgrade("base")
    assert migrator.current() is None
    migrator.upgrade()
    migrator.check()
    assert migrator.parse(["current"]) == 0
    assert capsys.readouterr().out.strip() == StorageSchema.REVISION
