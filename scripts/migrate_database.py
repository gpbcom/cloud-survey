from __future__ import annotations

# Standard Library Imports.
import argparse
import asyncio
import sys
from logging import Logger, getLogger
from pathlib import Path
from typing import ClassVar, List, Optional, Sequence

# Third Party Imports.
from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected, CommandError
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.ext.asyncio import create_async_engine

# First Party Imports.
from logger import setup_logging
from models.configuration.storage.storage_settings import StorageSettings
from scripts.enums import MigrationCommand
from scripts.exception import MigrationError
from storage.engine.settings_reader import StorageSettingsReader
from storage.exception import StorageError
from storage.storage import Storage
from taxonomy.exception import TaxonomyError


class DatabaseMigrator:
    """Migrate the schema of the storage database with Alembic: `uv run migrate-db <command>`.

    Attributes:
        MIGRATIONS_DIR (ClassVar[Path]): The Alembic environment and its migrations (`scripts/migrations`).
        settings (StorageSettings): The storage settings: the database to migrate.
        logger (Logger): The migrator logger.
        url (str): The database URL without its password, for the logs.
        config (Config): The Alembic configuration, built without `alembic.ini`.

    Notes:
        - The Alembic commands run their own event loop: from asynchronous code, call them in a thread
          (`asyncio.to_thread`).
        - An upgrade to the head applies the seed of the unified taxonomy afterwards (see `TaxonomySeeder`).
    """

    MIGRATIONS_DIR: ClassVar[Path] = Path(__file__).parent / "migrations"

    def __init__(self, settings: Optional[StorageSettings] = None, logger: Optional[Logger] = None) -> None:
        """Initialize the migrator.

        Args:
            settings (Optional[StorageSettings]): The storage settings, read from the environment by default.
            logger (Optional[Logger]): The migrator logger.
        """
        self.logger = logger if logger else getLogger(__name__)
        reader = StorageSettingsReader(self.logger)
        self.settings = settings if settings else reader.read()
        self.url = reader.safe_url(self.settings.url)
        self.config = Config()
        self.config.set_main_option("script_location", str(self.MIGRATIONS_DIR))
        # The configuration interpolates `%`: an escaped password reaches the driver unchanged.
        self.config.set_main_option("sqlalchemy.url", self.settings.url.replace("%", "%%"))
        self.logger.debug("Migrator of %s ready (migrations in %s).", self.url, self.MIGRATIONS_DIR)

    ############################
    # Internal Helpers Methods #
    ############################

    def _read_revision(self, connection: Connection) -> Optional[str]:
        """Read the migration revision of the database.

        Args:
            connection (Connection): The synchronous facade of an asyncpg connection.

        Returns:
            Optional[str]: The revision, `None` when no migration was applied.
        """
        self.logger.debug("Reading the migration revision of %s.", self.url)
        return MigrationContext.configure(connection).get_current_revision()

    async def _current(self) -> Optional[str]:
        """Read the migration revision of the database, with a dedicated engine.

        Returns:
            Optional[str]: The revision, `None` when no migration was applied.
        """
        self.logger.debug("Connecting to %s to read its revision.", self.url)
        engine = create_async_engine(self.settings.url, poolclass=pool.NullPool)
        try:
            async with engine.connect() as connection:
                return await connection.run_sync(self._read_revision)
        finally:
            await engine.dispose()

    async def _seed(self, force: bool) -> bool:
        """Apply the seed of the unified taxonomy and the curated bundle, with a dedicated storage.

        Args:
            force (bool): Whether the seeds are applied even when unchanged.

        Returns:
            bool: Whether one was applied.
        """
        self.logger.debug("Seeding the taxonomy and the curated catalogues of %s.", self.url)
        async with Storage(self.settings, self.logger) as storage:
            seeded = await storage.seeder.seed(force)
            curated = await storage.curated_seeder.seed(force=force)
            return seeded or bool(curated)

    def _next_revision_id(self) -> str:
        """Get the identifier of a new migration: the number following the head.

        Returns:
            str: The 4-digit number following the head revision, `0001` without any migration.
        """
        self.logger.debug("Numbering a new migration after the head of %s.", self.MIGRATIONS_DIR)
        head = ScriptDirectory.from_config(self.config).get_current_head()
        return f"{int(head) + 1:04d}" if head and head.isdigit() else "0001"

    def _arguments(self, argv: Optional[Sequence[str]]) -> argparse.Namespace:
        """Parse the command line.

        Args:
            argv (Optional[Sequence[str]]): The arguments, those of the process by default.

        Returns:
            argparse.Namespace: The command and its options.
        """
        self.logger.debug("Parsing the command line %s.", list(argv) if argv is not None else sys.argv[1:])
        parser = argparse.ArgumentParser(prog="migrate-db", description="Migrate the crawler storage database.")
        commands = parser.add_subparsers(dest="command", required=True)
        upgrade = commands.add_parser(
            MigrationCommand.UPGRADE, help="apply the migrations up to a revision (head by default)"
        )
        upgrade.add_argument("revision", nargs="?", default="head")
        downgrade = commands.add_parser(
            MigrationCommand.DOWNGRADE, help="revert the migrations down to a revision (base: all)"
        )
        downgrade.add_argument("revision")
        commands.add_parser(MigrationCommand.CURRENT, help="show the revision of the database")
        commands.add_parser(MigrationCommand.HISTORY, help="list the migrations")
        revision = commands.add_parser(MigrationCommand.REVISION, help="write a new migration")
        revision.add_argument("-m", "--message", required=True)
        revision.add_argument("--autogenerate", action="store_true", help="compare the tables with the database")
        commands.add_parser(MigrationCommand.CHECK, help="fail when the tables and the database schema differ")
        seed = commands.add_parser(MigrationCommand.SEED, help="apply the seed of the unified taxonomy")
        seed.add_argument("--force", action="store_true", help="apply the seed even when it did not change")
        return parser.parse_args(argv)

    ############################
    # Publicly Exposed Methods #
    ############################

    def seed(self, force: bool = False) -> bool:
        """Apply the seed of the unified taxonomy (`conf/taxonomy/`), when it changed since the last seed.

        Args:
            force (bool): Whether the seed is applied even when unchanged.

        Returns:
            bool: Whether the seed was applied.

        Raises:
            MigrationError: If the seed cannot be loaded or written.
        """
        try:
            seeded = asyncio.run(self._seed(force))
        except (StorageError, TaxonomyError, SQLAlchemyError, OSError) as e:
            self.logger.error("The taxonomy of %s cannot be seeded: %s", self.url, e)
            raise MigrationError(MigrationCommand.SEED, str(e)) from e
        self.logger.info("The taxonomy of %s is %s.", self.url, "seeded" if seeded else "already up to date")
        return seeded

    def upgrade(self, revision: str = "head") -> None:
        """Apply the migrations up to a revision.

        Args:
            revision (str): The target revision, the last one by default.

        Raises:
            MigrationError: If the migrations cannot be applied.
        """
        self.logger.info("Upgrading the database %s to %s.", self.url, revision)
        try:
            command.upgrade(self.config, revision)
        except (CommandError, SQLAlchemyError, OSError) as e:
            self.logger.error("The database %s cannot be upgraded to %s: %s", self.url, revision, e)
            raise MigrationError(MigrationCommand.UPGRADE, str(e)) from e
        self.logger.info("The database %s is at revision %s.", self.url, revision)
        if revision == "head":
            self.seed()

    def downgrade(self, revision: str) -> None:
        """Revert the migrations down to a revision.

        Args:
            revision (str): The target revision, `base` to revert every migration.

        Raises:
            MigrationError: If the migrations cannot be reverted.
        """
        self.logger.warning("Downgrading the database %s to %s.", self.url, revision)
        try:
            command.downgrade(self.config, revision)
        except (CommandError, SQLAlchemyError, OSError) as e:
            self.logger.error("The database %s cannot be downgraded to %s: %s", self.url, revision, e)
            raise MigrationError(MigrationCommand.DOWNGRADE, str(e)) from e
        self.logger.info("The database %s is at revision %s.", self.url, revision)

    def current(self) -> Optional[str]:
        """Read the migration revision of the database.

        Returns:
            Optional[str]: The revision, `None` when no migration was applied.

        Raises:
            MigrationError: If the database cannot be reached.
        """
        try:
            revision = asyncio.run(self._current())
        except (SQLAlchemyError, OSError) as e:
            self.logger.error("The revision of the database %s cannot be read: %s", self.url, e)
            raise MigrationError(MigrationCommand.CURRENT, str(e)) from e
        self.logger.info("The database %s is at revision %s.", self.url, revision or "none")
        return revision

    def history(self) -> List[str]:
        """List the migrations, the first one first.

        Returns:
            List[str]: Each migration as `<revision>: <message>`.
        """
        scripts = ScriptDirectory.from_config(self.config)
        migrations = [f"{script.revision}: {script.doc}" for script in scripts.walk_revisions()][::-1]
        self.logger.debug("%d migrations found in %s.", len(migrations), self.MIGRATIONS_DIR)
        return migrations

    def revision(self, message: str, autogenerate: bool = False) -> Path:
        """Write a new migration, numbered after the head.

        Args:
            message (str): What the migration does.
            autogenerate (bool): Whether its operations are generated by comparing the tables with the database.

        Returns:
            Path: The migration file, to review.

        Raises:
            MigrationError: If the migration cannot be written.
        """
        revision_id = self._next_revision_id()
        try:
            written = command.revision(self.config, message=message, autogenerate=autogenerate, rev_id=revision_id)
        except (CommandError, SQLAlchemyError, OSError) as e:
            self.logger.error("The migration %r cannot be written: %s", message, e)
            raise MigrationError(MigrationCommand.REVISION, str(e)) from e
        scripts = written if isinstance(written, list) else [written]
        path = Path(scripts[0].path) if scripts and scripts[0] is not None else self.MIGRATIONS_DIR
        self.logger.info("Migration %s written to %s: review it before applying it.", revision_id, path)
        return path

    def check(self) -> None:
        """Check that the tables of the code and the database schema do not differ.

        Raises:
            MigrationError: If they differ (a migration is missing) or the database cannot be reached.
        """
        try:
            command.check(self.config)
        except AutogenerateDiffsDetected as e:
            self.logger.error("The database %s schema differs from the tables: %s", self.url, e)
            raise MigrationError(MigrationCommand.CHECK, str(e)) from e
        except (CommandError, SQLAlchemyError, OSError) as e:
            self.logger.error("The database %s schema cannot be checked: %s", self.url, e)
            raise MigrationError(MigrationCommand.CHECK, str(e)) from e
        self.logger.info("The database %s schema matches the tables.", self.url)

    def parse(self, argv: Optional[Sequence[str]] = None) -> int:
        """Run a command of the command line.

        Args:
            argv (Optional[Sequence[str]]): The arguments, those of the process by default.

        Returns:
            int: The exit code: 0 on success, 1 when the command failed (logged).
        """
        arguments = self._arguments(argv)
        try:
            match MigrationCommand(arguments.command):
                case MigrationCommand.UPGRADE:
                    self.upgrade(arguments.revision)
                case MigrationCommand.DOWNGRADE:
                    self.downgrade(arguments.revision)
                case MigrationCommand.CURRENT:
                    print(self.current() or "none")
                case MigrationCommand.HISTORY:
                    print("\n".join(self.history()))
                case MigrationCommand.REVISION:
                    print(self.revision(arguments.message, arguments.autogenerate))
                case MigrationCommand.CHECK:
                    self.check()
                case MigrationCommand.SEED:
                    self.seed(arguments.force)
        except MigrationError as e:
            self.logger.error("%s", e)
            return 1
        return 0


def main() -> int:
    """Console entry point of `uv run migrate-db`.

    Returns:
        int: The exit code.
    """
    setup_logging()
    return DatabaseMigrator().parse(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
